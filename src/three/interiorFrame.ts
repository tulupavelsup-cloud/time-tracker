/**
 * Подгонка интерьеров (шахта, банк) под экран.
 *
 * Оба зала собирались под вертикальный кадр телефона, а камера у них стоит
 * ВНУТРИ зала и смотрит вдоль него сверху. Пока оболочка обрывалась у ближней
 * кромки телефонного кадра, на любом экране пошире (десктоп, планшет, поворот
 * телефона) её было видно СНАРУЖИ: по краям кадра — наружные грани стен, а по
 * углам сплошной фон, и зал читался коробкой, поставленной посреди пустоты.
 *
 * Отсюда два правила, общих для обоих интерьеров:
 *   • оболочка заходит ЗА камеру (SHELL_NEAR) и выше неё (SHELL_H) — куда бы ни
 *     смотрел луч из камеры, он упирается в стену, пол или свод, а не в фон.
 *     Кадр заполнен целиком при любом отношении сторон;
 *   • зал раздаётся вширь (spread) тем сильнее, чем шире экран. Без этого на
 *     широком экране он превращался бы в щель между двумя стенами вплотную к
 *     камере: заполнено, но смотреть не на что.
 */

import { useThree } from '@react-three/fiber';
import * as THREE from 'three';

/** Отношение сторон, под которое собран кадр интерьеров (телефон в портрете). */
const PORTRAIT = 0.5;

/**
 * Ближняя кромка оболочки по z. Камера интерьера стоит на z ≈ 4.6…6.8 (зависит
 * от уровня), так что пол и стены обязаны тянуться дальше неё.
 */
export const SHELL_NEAR = 10;

/** Высота стен оболочки: камера поднимается до y ≈ 10, стены должны быть выше. */
export const SHELL_H = 17;

/** Отношение сторон холста — интерьер подстраивается под него на лету. */
export function useAspect(): number {
  const size = useThree((s) => s.size);
  return size.height > 0 ? size.width / size.height : PORTRAIT;
}

/**
 * Во сколько раз шире базового должен быть зал на этом экране. Ступеньками по
 * 0.05: от ширины зала зависит вся раскладка породы и мебели, и пересобирать её
 * на каждый пиксель перетаскивания окна незачем.
 */
export function useSpread(): number {
  const aspect = useAspect();
  const k = THREE.MathUtils.clamp(aspect / PORTRAIT, 1, 2);
  return Math.round(k * 20) / 20;
}
