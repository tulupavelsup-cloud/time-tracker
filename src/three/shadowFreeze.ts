/**
 * Замороженные тени (чеклист оптимизации, пункты 2 и 3).
 *
 * Мир не двигается, солнце не двигается — значит тени всегда одни и те же, и
 * пересчитывать их вообще незачем. Раньше теневая карта перерисовывалась раз в
 * четыре кадра: сцена целиком прогонялась через видеочип второй раз, и каждый
 * четвёртый кадр стоил в полтора раза дороже остальных — отсюда и неровное
 * движение. Теперь теневой проход идёт только тогда, когда СОСТАВ сцены
 * изменился: при склейке (см. Baked), на входе в зону и выходе из неё, при
 * смене уровня и при повороте телефона. В обычном кадре его нет совсем.
 *
 * Условие у такой заморозки одно: движущееся не должно отбрасывать тень —
 * иначе тень отпечатается там, где деталь была в момент пересчёта, и останется
 * висеть в стороне от неё. Поэтому перед каждым пересчётом всё, помеченное
 * userData={LIVE} (вагонетки, крылья мельницы, качалка, герой), гасится по
 * castShadow. Мелочь эту в общем плане и не видно; заметен только герой, и ему
 * тень вернули отдельно и дёшево — мягким пятном на земле (см. HeroShadow).
 */

import { useEffect } from 'react';
import { useFrame, useThree } from '@react-three/fiber';
import type * as THREE from 'three';

/**
 * Сколько раз пересчитать тени после изменения сцены и с каким шагом в кадрах.
 * Одного раза мало: React дособирает сцену не за один кадр (склейка в Baked
 * происходит уже после первой отрисовки), и единственный ранний пересчёт мог
 * бы застать сцену недостроенной. Несколько редких пересчётов подряд стоят
 * пустяки, а промаха не оставляют.
 */
const BURST = 6;
const STEP = 4;

/**
 * Отладочный выключатель заморозки: `?freeze=0` — тени считаются раз в четыре
 * кадра, как до этой правки, и движущееся снова их отбрасывает. Нужен, чтобы
 * сравнивать картинку и цену кадра до и после В ОДНОЙ сборке.
 */
export const FREEZE_OFF =
  typeof location !== 'undefined' && new URLSearchParams(location.search).get('freeze') === '0';

/** Сколько пересчётов ещё должно пройти и сколько кадров прошло с запроса. */
let pending = 0;
let frame = 0;

/**
 * «Сцена изменилась — тени пересчитать». Вызывается из мест, где меняется
 * состав сцены: склейка, смена уровня зоны, вход внутрь и выход, ресайз.
 * Вызывать можно сколько угодно часто — лишние вызовы просто продлевают серию.
 */
export function refreshShadows() {
  pending = BURST;
  frame = 0;
}

/**
 * Гасит тени у всего движущегося. Обходит сцену до узлов с userData.live и
 * снимает castShadow со всей их ветки. Дальше внутрь спускаться незачем —
 * живое живое целиком.
 */
function hushLive(node: THREE.Object3D) {
  if ((node.userData as { live?: boolean } | undefined)?.live) {
    node.traverse((n) => {
      n.castShadow = false;
    });
    return;
  }
  for (const child of node.children) hushLive(child);
}

/**
 * Держит теневую карту замороженной и пересчитывает её только по запросу.
 * Ставится один раз внутри <Canvas> — общий и для карты, и для интерьеров.
 */
export function ShadowFreeze() {
  const width = useThree((s) => s.size.width);
  const height = useThree((s) => s.size.height);

  // При монтировании — серия пересчётов (теневая карта ещё пуста), а дальше на
  // каждый поворот телефона: кадр меняется, и вместе с ним состав нарисованного.
  useEffect(() => {
    refreshShadows();
  }, [width, height]);

  useFrame((state) => {
    const map = state.gl.shadowMap;
    // три.js по умолчанию перерисовывает тени каждый кадр — забираем управление
    if (map.autoUpdate) map.autoUpdate = false;
    // ?freeze=0 — прежний темп: тени пересчитываются раз в четыре кадра
    if (FREEZE_OFF) {
      frame++;
      if (frame % STEP === 0) map.needsUpdate = true;
      return;
    }
    if (pending <= 0) return;
    if (frame % STEP === 0) {
      hushLive(state.scene);
      map.needsUpdate = true;
      pending--;
    }
    frame++;
  });

  return null;
}
